import '../../../attendance/domain/entities/attendance_event.dart';
import '../../domain/entities/local_queue_item.dart';
import '../../domain/entities/sync_status.dart';

/// Database mapping model for [LocalQueueItem].
class LocalQueueItemModel extends LocalQueueItem {
  const LocalQueueItemModel({
    required super.localId,
    required super.idempotencyKey,
    super.sessionId,
    required super.tenantId,
    required super.employeeId,
    required super.userId,
    required super.eventType,
    required super.deviceReportedAt,
    required super.timezoneOffsetMinutes,
    required super.monotonicBootTimeMs,
    required super.bootSessionId,
    super.isRebootDetected,
    super.locationId,
    super.latitude,
    super.longitude,
    super.accuracyMeters,
    super.wifiBssid,
    super.wifiSsid,
    super.wifiSignalStatus,
    super.encryptedPayloadBlob,
    required super.appliedPolicyVersion,
    required super.appliedPolicyMode,
    super.deviceId,
    super.metadataJson,
    required super.sequenceNumber,
    super.syncStatus,
    super.conflictBundleId,
    super.retryCount,
    super.lastAttemptedAt,
    super.lastErrorMessage,
    super.lastErrorStatusCode,
    super.serverEventId,
    required super.createdAt,
    required super.updatedAt,
  });

  factory LocalQueueItemModel.fromEntity(LocalQueueItem entity) {
    return LocalQueueItemModel(
      localId: entity.localId,
      idempotencyKey: entity.idempotencyKey,
      sessionId: entity.sessionId,
      tenantId: entity.tenantId,
      employeeId: entity.employeeId,
      userId: entity.userId,
      eventType: entity.eventType,
      deviceReportedAt: entity.deviceReportedAt,
      timezoneOffsetMinutes: entity.timezoneOffsetMinutes,
      monotonicBootTimeMs: entity.monotonicBootTimeMs,
      bootSessionId: entity.bootSessionId,
      isRebootDetected: entity.isRebootDetected,
      locationId: entity.locationId,
      latitude: entity.latitude,
      longitude: entity.longitude,
      accuracyMeters: entity.accuracyMeters,
      wifiBssid: entity.wifiBssid,
      wifiSsid: entity.wifiSsid,
      wifiSignalStatus: entity.wifiSignalStatus,
      encryptedPayloadBlob: entity.encryptedPayloadBlob,
      appliedPolicyVersion: entity.appliedPolicyVersion,
      appliedPolicyMode: entity.appliedPolicyMode,
      deviceId: entity.deviceId,
      metadataJson: entity.metadataJson,
      sequenceNumber: entity.sequenceNumber,
      syncStatus: entity.syncStatus,
      conflictBundleId: entity.conflictBundleId,
      retryCount: entity.retryCount,
      lastAttemptedAt: entity.lastAttemptedAt,
      lastErrorMessage: entity.lastErrorMessage,
      lastErrorStatusCode: entity.lastErrorStatusCode,
      serverEventId: entity.serverEventId,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }

  factory LocalQueueItemModel.fromRow(Map<String, dynamic> row) {
    return LocalQueueItemModel(
      localId: row['local_id'] as String,
      idempotencyKey: row['idempotency_key'] as String,
      sessionId: row['session_id'] as String?,
      tenantId: row['tenant_id'] as String,
      employeeId: row['employee_id'] as String,
      userId: row['user_id'] as String,
      eventType: AttendanceEventTypeX.fromBackendString(
          row['event_type'] as String? ?? 'CHECK_IN'),
      deviceReportedAt:
          DateTime.parse(row['device_reported_at'] as String).toUtc(),
      timezoneOffsetMinutes: (row['timezone_offset_minutes'] as num).toInt(),
      monotonicBootTimeMs: (row['monotonic_boot_time_ms'] as num).toInt(),
      bootSessionId: row['boot_session_id'] as String? ?? 'unknown',
      isRebootDetected: (row['is_reboot_detected'] as int? ?? 0) == 1,
      locationId: row['location_id'] as String?,
      latitude: (row['latitude'] as num?)?.toDouble(),
      longitude: (row['longitude'] as num?)?.toDouble(),
      accuracyMeters: (row['accuracy_meters'] as num?)?.toDouble(),
      wifiBssid: row['wifi_bssid'] as String?,
      wifiSsid: row['wifi_ssid'] as String?,
      wifiSignalStatus: row['wifi_signal_status'] as String? ?? 'AVAILABLE',
      encryptedPayloadBlob: row['encrypted_payload_blob'] as String?,
      appliedPolicyVersion:
          (row['applied_policy_version'] as num? ?? 1).toInt(),
      appliedPolicyMode: row['applied_policy_mode'] as String? ?? 'MANUAL',
      deviceId: row['device_id'] as String?,
      metadataJson: row['metadata_json'] as String? ?? '{}',
      sequenceNumber: (row['sequence_number'] as num).toInt(),
      syncStatus: SyncStatus.fromDbString(
          row['sync_status'] as String? ?? 'PENDING_SYNC'),
      conflictBundleId: row['conflict_bundle_id'] as String?,
      retryCount: (row['retry_count'] as num? ?? 0).toInt(),
      lastAttemptedAt: row['last_attempted_at'] != null
          ? DateTime.parse(row['last_attempted_at'] as String).toUtc()
          : null,
      lastErrorMessage: row['last_error_message'] as String?,
      lastErrorStatusCode: (row['last_error_status_code'] as num?)?.toInt(),
      serverEventId: row['server_event_id'] as String?,
      createdAt: DateTime.parse(row['created_at'] as String).toUtc(),
      updatedAt: DateTime.parse(row['updated_at'] as String).toUtc(),
    );
  }

  Map<String, dynamic> toRow() {
    return {
      'local_id': localId,
      'idempotency_key': idempotencyKey,
      'session_id': sessionId,
      'tenant_id': tenantId,
      'employee_id': employeeId,
      'user_id': userId,
      'event_type': eventType.toBackendString(),
      'device_reported_at': deviceReportedAt.toUtc().toIso8601String(),
      'timezone_offset_minutes': timezoneOffsetMinutes,
      'monotonic_boot_time_ms': monotonicBootTimeMs,
      'boot_session_id': bootSessionId,
      'is_reboot_detected': isRebootDetected ? 1 : 0,
      'location_id': locationId,
      'latitude': latitude,
      'longitude': longitude,
      'accuracy_meters': accuracyMeters,
      'wifi_bssid': wifiBssid,
      'wifi_ssid': wifiSsid,
      'wifi_signal_status': wifiSignalStatus,
      'encrypted_payload_blob': encryptedPayloadBlob,
      'applied_policy_version': appliedPolicyVersion,
      'applied_policy_mode': appliedPolicyMode,
      'device_id': deviceId,
      'metadata_json': metadataJson,
      'sequence_number': sequenceNumber,
      'sync_status': syncStatus.toDbString(),
      'conflict_bundle_id': conflictBundleId,
      'retry_count': retryCount,
      'last_attempted_at': lastAttemptedAt?.toUtc().toIso8601String(),
      'last_error_message': lastErrorMessage,
      'last_error_status_code': lastErrorStatusCode,
      'server_event_id': serverEventId,
      'created_at': createdAt.toUtc().toIso8601String(),
      'updated_at': updatedAt.toUtc().toIso8601String(),
    };
  }
}
