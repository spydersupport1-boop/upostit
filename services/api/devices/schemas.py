"""Pydantic schemas for device registration, management, and binding."""

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class DevicePlatform(StrEnum):
    """Supported device operating system platforms."""

    ANDROID = "ANDROID"
    IOS = "IOS"
    WEB = "WEB"
    OTHER = "OTHER"


class DeviceStatus(StrEnum):
    """Device binding lifecycle statuses."""

    PENDING_APPROVAL = "PENDING_APPROVAL"
    ACTIVE = "ACTIVE"
    REVOKED = "REVOKED"
    REPLACED = "REPLACED"


class DeviceRegisterRequest(BaseModel):
    """Payload for registering a device by an authenticated employee."""

    device_id: str = Field(
        ...,
        min_length=8,
        max_length=128,
        description="Unique device hardware or install identifier generated by client secure storage.",
    )
    platform: DevicePlatform = Field(
        ...,
        description="Operating system platform (ANDROID, IOS, WEB, OTHER).",
    )
    device_model: str | None = Field(
        default=None,
        max_length=100,
        description="Hardware model name (e.g. Pixel 8, iPhone 15 Pro).",
    )
    os_name: str | None = Field(
        default=None,
        max_length=50,
        description="OS Name (e.g. Android, iOS).",
    )
    os_version: str | None = Field(
        default=None,
        max_length=50,
        description="OS Version string (e.g. 14.0, 17.4.1).",
    )
    app_version: str | None = Field(
        default=None,
        max_length=50,
        description="Installed client application version.",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Extensible device telemetry metadata.",
    )


class DeviceResponse(BaseModel):
    """Safe public device metadata (never exposes raw identifier or hash)."""

    id: uuid.UUID
    tenant_id: uuid.UUID
    employee_id: uuid.UUID
    platform: str
    device_model: str | None = None
    os_name: str | None = None
    os_version: str | None = None
    app_version: str | None = None
    status: str
    registered_at: datetime
    last_seen_at: datetime | None = None
    revoked_at: datetime | None = None
    revocation_reason: str | None = None
    replacement_for_device_id: uuid.UUID | None = None
    replacement_approved_at: datetime | None = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class DeviceRegistrationResponse(BaseModel):
    """Response returned upon device registration attempt."""

    device: DeviceResponse
    requires_approval: bool = False
    message: str


class DeviceListResponse(BaseModel):
    """Paginated collection of registered tenant devices."""

    items: list[DeviceResponse]
    total: int
    limit: int
    offset: int


class DeviceRevokeRequest(BaseModel):
    """Administrative request to revoke a registered device."""

    reason: str = Field(
        ...,
        min_length=3,
        max_length=500,
        description="Mandatory justification for device revocation.",
    )


class DeviceReplacementApprovalRequest(BaseModel):
    """Administrative request to approve a pending device replacement."""

    notes: str | None = Field(
        default=None,
        max_length=500,
        description="Optional administrative review notes.",
    )


class DeviceStatusResponse(BaseModel):
    """Current device binding status for an employee."""

    is_bound: bool
    status: str | None = None
    device: DeviceResponse | None = None


class DeviceSecurityStatusResponse(BaseModel):
    """Device security posture and offline encryption metadata."""

    is_bound: bool
    status: str
    is_revoked: bool
    revoked_at: datetime | None = None
    revocation_reason: str | None = None
    platform: str | None = None
    device_model: str | None = None
    registered_at: datetime | None = None
    encryption_algorithm_supported: str = "SQLCIPHER_PAGE_AES256"
    min_app_version: str = "1.0.0"


class DeviceReRegisterRequest(BaseModel):
    """Payload to safely re-register a mobile device after hardware key wipe or replacement."""

    device_id: str = Field(
        ...,
        min_length=8,
        max_length=128,
        description="New or re-initialized device hardware identifier.",
    )
    platform: DevicePlatform = Field(
        ...,
        description="Operating system platform.",
    )
    re_registration_reason: str = Field(
        ...,
        min_length=3,
        max_length=500,
        description="Reason for re-registration (e.g. OS upgrade, key wipe, factory reset).",
    )
    device_model: str | None = None
    os_name: str | None = None
    os_version: str | None = None
    app_version: str | None = None

